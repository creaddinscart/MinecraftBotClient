_current_lang = "zh"

def set_language(lang):
    global _current_lang
    _current_lang = lang if lang in _translations else "zh"

def t(key, **kwargs):
    d = _translations.get(_current_lang, _translations["zh"])
    s = d.get(key)
    if s is None:
        s = _translations["zh"].get(key, key)
    try:
        return s.format(**kwargs) if kwargs else s
    except Exception:
        return s
