def set_language(lang):
    global _current_lang
    if lang in _translations:
        _current_lang = lang

def t(key, **kwargs):
    strings = _translations.get(_current_lang, _translations["en"])
    text = strings.get(key, _translations["en"].get(key, key))
    if kwargs:
        return text.format(**kwargs)
    return text
